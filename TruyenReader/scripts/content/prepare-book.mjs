import { DatabaseSync } from 'node:sqlite';
import { createHash } from 'node:crypto';
import {
  copyFileSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
  existsSync,
  renameSync,
  rmSync,
  readdirSync,
} from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SCHEMA, parseBookText } from '../../src/domain/book-format.ts';

export function createBundle(inputPath, outputDir) {
  const catalogDb = resolve(outputDir, 'catalog.db');
  const bookMeta = resolve(outputDir, 'book-meta.json');
  if (!existsSync(inputPath)) {
    if (existsSync(catalogDb) && existsSync(bookMeta)) {
      console.log('Dùng dữ liệu hiện có trong assets/ (bỏ qua input/truyen.json vì ưu tiên API).');
      return JSON.parse(readFileSync(bookMeta, 'utf8'));
    }
    throw new Error(
      `Chưa có ${inputPath}. Hãy chờ tải xong, chép truyen.json vào thư mục input rồi build lại.`,
    );
  }
  const text = readFileSync(inputPath, 'utf8');
  const book = parseBookText(text);
  const hash = createHash('sha256').update(text).digest('hex').slice(0, 20);
  mkdirSync(outputDir, { recursive: true });
  const chunkSize = 50;
  const contentDir = resolve(outputDir, 'content');
  mkdirSync(contentDir, { recursive: true });
  const chunks = [];
  for (let offset = 0; offset < book.chapters.length; offset += chunkSize) {
    const rows = book.chapters
      .slice(offset, offset + chunkSize)
      .map((c) => ({ id: c.id, content: c.content }));
    const data = JSON.stringify(rows);
    const digest = createHash('sha256').update(data).digest('hex');
    const name = `chunk-${offset / chunkSize}-${digest.slice(0, 16)}.book`;
    writeFileSync(resolve(contentDir, name), data);
    chunks.push({
      file: `content/${name}`,
      hash: digest,
      bytes: Buffer.byteLength(data),
      count: rows.length,
    });
  }
  const temp = resolve(outputDir, 'catalog.db.tmp');
  rmSync(temp, { force: true });
  const db = new DatabaseSync(temp);
  try {
    db.exec(SCHEMA);
    db.exec('BEGIN');
    db.prepare('INSERT INTO books (id,title,total,source,updated_at) VALUES (?,?,?,?,?)').run(
      book.id,
      book.title,
      book.chapters.length,
      book.source,
      new Date().toISOString(),
    );
    const statement = db.prepare(
      'INSERT INTO chapters (id,book_id,position,number,title,content,url,search_title) VALUES (?,?,?,?,?,?,?,?)',
    );
    for (const c of book.chapters)
      statement.run(c.id, book.id, c.position, c.number, c.title, '', c.url, c.searchTitle);
    db.exec('COMMIT');
    db.exec('VACUUM');
  } finally {
    db.close();
  }
  renameSync(temp, resolve(outputDir, 'catalog.db'));
  const databaseHash = createHash('sha256')
    .update(readFileSync(resolve(outputDir, 'catalog.db')))
    .digest('hex');
  const meta = {
    hash,
    databaseHash,
    demo: false,
    title: book.title,
    count: book.chapters.length,
    bookId: book.id,
    format: 'chunks-v1',
    chunkSize,
    chunks,
  };
  const manifest = `// Generated by prepare-book.mjs. Static require registers assets; loading happens on demand.\nexport const contentAssets: number[] = [\n${chunks.map((c) => `  require('./${c.file}'),`).join('\n')}\n];\n`;
  writeFileSync(resolve(outputDir, 'content-assets.ts'), manifest);
  writeFileSync(resolve(outputDir, 'book-meta.json'), JSON.stringify(meta, null, 2) + '\n');
  // Keep only active chunk files so EAS uploads no superseded copies of the book.
  const active = new Set(chunks.map((c) => c.file.split('/').pop()));
  for (const name of readdirSync(contentDir))
    if (name.endsWith('.book') && !active.has(name)) rmSync(resolve(contentDir, name));
  return meta;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
  try {
    const meta = createBundle(resolve(root, 'input/truyen.json'), resolve(root, 'assets'));
    console.log(`${meta.title}: ${meta.count} mục. Dữ liệu SQLite đã sẵn sàng.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

// Refresh the packaged reference data; never fetch or parse web pages during builds.
const knowledgeRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const knowledgeSource = resolve(knowledgeRoot, '../TruyenBackend/data/cultivation/de-ba.json');
if (existsSync(knowledgeSource)) {
  mkdirSync(resolve(knowledgeRoot, 'assets/knowledge'), { recursive: true });
  copyFileSync(knowledgeSource, resolve(knowledgeRoot, 'assets/knowledge/de-ba.json'));
}
